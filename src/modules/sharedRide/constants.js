export const getHoldMinutes = () => {
  const raw = Number(process.env.SHARED_RIDE_HOLD_MINUTES);
  return Number.isFinite(raw) && raw > 0 ? raw : 10;
};

export const getDefaultDeviationKm = () => {
  const raw = Number(process.env.SHARED_RIDE_DEFAULT_DEVIATION_KM);
  return Number.isFinite(raw) && raw > 0 ? raw : 2;
};
